def theme_guide(key):
    theme = THEMES[key]
    body = section('recommendation', '今回の推奨と、その理由',
        note(theme['recommendation'], theme['reason'])
        + '<p class="subtle">以下は比較条件を仮定した設計・運用例です。期限・頻度・数値・役割は検討用で、確定要件や実際の担当・設定・日程を表しません。サービスの保証値とも異なり、組み合わせの実機動作は別途検証が必要です。</p>')
    body += section('practice', '運用を検討するときのベストプラクティス', steps(theme['practices']))
    body += section('alternatives', '代替案を選ぶ条件', table(
        ['代替案', 'こちらを選ぶ場合', '引き受ける条件'], theme['alternatives'],
        '現在の前提が変わったときの選び方'))
    body += section('next', '追加調査・試作の例と確認観点', definition([
        ('試作・調査の例', theme['next']), ('比較のための確認観点', theme['gate'])]))
    return body
